// Snake Explorers — content inventory, computed from the data (not hand-counted).
//   node tools/content-inventory.cjs            prints Markdown
//   node tools/content-inventory.cjs --write    also writes explorers/CONTENT.md
// "Authored" = hand-written records in bank.js/content.js (plus the curated level
// list). "Reachable" = distinct question ids a mode can deal, found by building
// many rounds; for generator-based families that is a sample, marked "≥".
const fs = require("fs"), path = require("path");
const L = require("../explorers/js/logic.js");
const C = require("../explorers/js/content.js");
const B = require("../explorers/js/bank.js");
const I = C._internals;

const sum = (a) => a.reduce((x, y) => x + y, 0);
const uniq = (a) => Array.from(new Set(a));
const patternRules = uniq(Object.values(I.PAT_MODES).flat());
const AUTHORED = {
  word: [
    ["Snack Hunt foods (find by name)", B.FOODS.length],
    ["Snack Hunt written clues", B.FOODS.length],
    ["Snack Hunt “find a food that…” clues (several right answers)", B.FOOD_CATEGORIES.length],
    ["Letter Line words", sum(Object.values(B.WORDS).map(w => w.length))],
    ["Sentence Builder sentences", sum(Object.values(B.SENTENCES).map(w => w.length))]
  ],
  number: [
    ["Everyday comparisons (heavier, longer, holds more…)", B.COMPARE_AMOUNTS.length],
    ["Story problems (many multi-step)", B.STORY_PROBLEMS.length],
    ["Word-problem templates (numbers generated)", 8],
    ["Number-pattern rules", 10]
  ],
  pattern: [
    ["Pattern Path rules (repeating, missing piece, odd one out)", patternRules.length],
    ["Shape Sort rule sets (kinds, not color/shape combinations)", uniq(Object.values(I.SORT_RULES).flat().map(r => r.kind)).length],
    ["Growing-pattern rules", 7],
    ["Turned-shape base shapes", 8]
  ],
  nature: [
    ["Animals (fact, “Who am I?” riddle, recall question)", B.ANIMALS.length],
    ["Animal habitat placements", B.ANIMALS.filter(a => a.homes.length).length],
    ["Life cycles and natural cycles", Object.keys(B.CYCLES).length],
    ["Food chains", B.CHAINS.length],
    ["Living / not-living items", B.LIVING.length],
    ["Food-chain and living-things questions", B.NATURE_QUESTIONS.length]
  ],
  logic: [
    ["Code the Snake levels (hand-made)", 13],
    ["Code the Snake levels (curated from a seeded, solver-checked generator)", sum(Object.values(C.LEVELS).map(l => l.length)) - 13]
  ],
  everyday: [
    ["Routines to put in order", Object.keys(B.ROUTINES).length],
    ["Weather scenarios", B.WEATHER.length],
    ["Safety scenarios (several safe answers)", B.SAFETY.length],
    ["Packing lists (with a Challenge twist)", B.PACKING.length],
    ["Kindness scenarios (several kind answers)", B.KIND.length],
    ["Tidy-up items (some fit more than one room)", B.TIDY.length]
  ]
};
const GENERATED = /^(count|match|sum|diff|double|more|less|1more|1less|add|tens|seq|gt|sub|miss|msub|two|wp|sums|share|pairs|groups|array|half|rem|third|sym|rot|grow|pred|pred5|bump|fix)$/;
const CONTAINER = /^(habset|rooms)$/;

function reachable(aid, mode, n) {
  const fams = {};
  for (let s = 0; s < n; s++) C.buildRound(aid, mode, s * 7919 + 1).forEach(p => p.cids.forEach(c => {
    const f = c.split(":")[0];
    if (CONTAINER.test(f) || c === "hunt-explore") return;
    (fams[f] = fams[f] || new Set()).add(c);
  }));
  let authored = 0, generated = 0;
  for (const [f, set] of Object.entries(fams)) { if (GENERATED.test(f)) generated += set.size; else authored += set.size; }
  return { authored, generated, round: C.buildRound(aid, mode, 1).length };
}

let md = "# Snake Explorers — content inventory\n\n";
md += "_Generated by `node tools/content-inventory.cjs --write` from the content files. Counts are semantic: the same question with shuffled answers, other colors, or other names is counted once._\n\n";
md += "## Authored items by world\n\n| World | Authored items | What they are |\n|---|---:|---|\n";
for (const w of C.WORLDS) {
  const rows = AUTHORED[w.id];
  md += `| ${w.name} | **${sum(rows.map(r => r[1]))}** | ${rows.map(r => r[0] + ": " + r[1]).join("; ")} |\n`;
}
md += "\n## Distinct questions each activity can deal, by mode\n\n";
md += "Authored = distinct hand-written questions reachable in that mode. Generated = distinct generated questions seen while building 400 rounds (a sample of a larger space, so shown as ≥). Round = questions per round.\n\n";
md += "| World | Activity | Explore (authored / generated / round) | Practice | Challenge |\n|---|---|---|---|---|\n";
for (const a of C.ACTIVITIES) {
  const cells = L.MODES.map(m => { const r = reachable(a.id, m, 400); return `${r.authored} / ${r.generated ? "≥" + r.generated : "–"} / ${r.round}`; });
  md += `| ${C.WORLDS.find(w => w.id === a.world).name} | ${a.title}${a.isNew ? " (new)" : ""} | ${cells.join(" | ")} |\n`;
}
md += "\nSnack Hunt Explore is free exploration (eat any snack), so it has no questions to count.\n";
if (require.main === module) console.log(md);
if (require.main === module && process.argv.includes("--write")) fs.writeFileSync(path.join(__dirname, "..", "explorers", "CONTENT.md"), md);
module.exports = { AUTHORED };
